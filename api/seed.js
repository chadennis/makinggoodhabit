const BM = Object.fromEntries(B);

function sample(arr, n) {
  const res = [];
  const clone = [...arr];
  for (let i = 0; i < n && clone.length > 0; i++) {
    const idx = Math.floor(Math.random() * clone.length);
    res.push(clone.splice(idx, 1)[0]);
  }
  return res;
}

export default async function handler(req, res) {
  try {
    await ensureSchema();

    // 기존 문제 비우기 (초기화 후 재등록)
    await sql`TRUNCATE TABLE quiz_questions RESTART IDENTITY`;

    const list = [];

    // 1. 구몬 B단계 90자 (hanja1)
    for (const [g, m] of B) {
      const others = B.filter(x => x[0] !== g).map(x => x[1]);
      list.push({
        mode: "hanja1", q_type: "glyph", prompt: "이 한자의 훈과 음은?",
        glyph: g, answer: m, options: JSON.stringify(sample(others, 3)),
        explanation: `${g} = ${m}`
      });
    }

    // 2. 5급 150자 (hanja3)
    for (const [g, m] of G5) {
      const others = G5.filter(x => x[0] !== g).map(x => x[1]);
      list.push({
        mode: "hanja3", q_type: "glyph", prompt: "이 한자의 훈과 음은?",
        glyph: g, answer: m, options: JSON.stringify(sample(others, 3)),
        explanation: `${g} = ${m}`
      });
    }

    // 3. 세계사 24문제 (hist)
    for (const [q, a, w, e] of W) {
      list.push({
        mode: "hist", q_type: "history", prompt: q,
        glyph: null, answer: a, options: JSON.stringify(w),
        explanation: e
      });
    }

    // 4. 한자 모양 도전 (hanja2)
    for (const [p, a, d] of COMBO) {
      list.push({
        mode: "hanja2", q_type: "combine", prompt: "합치면 어떤 한자가 될까요?",
        glyph: p, answer: a, options: JSON.stringify([...d]),
        explanation: `${p} = ${a} (${BM[a] || ""})`
      });
    }
    for (const s of SIM) {
      const chars = [...s];
      for (const g of chars) {
        const simOthers = chars.filter(c => c !== g);
        const otherChars = B.map(x => x[0]).filter(c => !chars.includes(c));
        const needed = 3 - simOthers.length;
        const optsChars = [...simOthers, ...sample(otherChars, Math.max(0, needed))].slice(0, 3);
        const opts = optsChars.map(c => BM[c] || c);
        list.push({
          mode: "hanja2", q_type: "glyph", prompt: "비슷한 글자와 헷갈리지 마세요! 훈과 음은?",
          glyph: g, answer: BM[g] || g, options: JSON.stringify(opts),
          explanation: chars.map(c => `${c} ${BM[c] || ""}`).join(" / ")
        });
      }
    }

    // Bulk Insert (PostgreSQL jsonb_to_recordset으로 1회 일괄 적재)
    await sql`INSERT INTO quiz_questions (mode, q_type, prompt, glyph, answer, options, explanation)
      SELECT x.mode, x.q_type, x.prompt, x.glyph, x.answer, x.options::jsonb, x.explanation
      FROM jsonb_to_recordset(${JSON.stringify(list)}::jsonb)
      AS x(mode text, q_type text, prompt text, glyph text, answer text, options text, explanation text)`;

    return res.status(200).json({
      success: true,
      count: list.length,
      message: `성공적으로 ${list.length}개의 문제가 Neon DB에 등록되었습니다!`
    });
  } catch (e) {
    console.error(e);
    return res.status(500).json({ error: e.message });
  }
}
